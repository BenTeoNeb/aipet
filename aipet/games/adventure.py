def _all_required(node):
    """Strict structured outputs (OpenAI, Anthropic) want every property required: optional fields are
    sent empty ("" or []) and dropped by `_clean`."""
    if isinstance(node, dict):
        if node.get("type") == "object" and "properties" in node:
            node["required"] = list(node["properties"])
        for v in node.values():
            _all_required(v)
    elif isinstance(node, list):
        for v in node:
            _all_required(v)
    return node


