def _drop_empty(d: dict, *fields: str):
    for f in fields:
        if f in d and not d[f]:
            del d[f]


def _clean(graph: dict, difficulty: str) -> dict:
    """What the model often gets wrong and a program can fix (so the one repair is kept for the
    puzzles): empty optional fields, stray verbs, a way back missing, a key without its lock."""
    graph = upgrade(graph)
    graph["difficulty"] = difficulty
    graph["format"] = 2
    for a in graph.get("actions", []):
        for t in a.get("triggers", []):
            verb = ENGLISH_VERBS.get(t.get("verb", ""), t.get("verb", ""))
            t["verb"] = canonical_verb(verb) if canonical_verb(verb) != "other" else verb
            _drop_empty(t, "target")
        _drop_empty(a, "place", "not_yet", "hint")
        if a.get("points") in (None, ""):  # 0 is a value (a loss scores nothing)
            a.pop("points", None)
        a.setdefault("when", [])
    places = {p.get("id"): p for p in graph.get("places", [])}
    for p in graph.get("places", []):
        for x in p.get("exits", []):
            x.setdefault("when", [])
            _drop_empty(x, "door", "blocked")
            back = places.get(x.get("to"), {})
            if back and not any(b.get("to") == p["id"] for b in back.get("exits", [])):
                back.setdefault("exits", []).append({"to": p["id"], "label": f"vers {p.get('name', p['id'])}",
                                                     "dir": OPPOSITE.get(x.get("dir", ""), ""), "when": []})  # fmt: skip
        p["details"] = [d for d in p.get("details") or [] if d.get("text") or d.get("else")]
        for d in p["details"]:
            _drop_empty(d, "else")
        for v in list(p.get("variants") or []):
            if not v.get("when"):
                p["variants"].remove(v)
        p["decor"] = [x for x in p.get("decor") or [] if x]
        _drop_empty(p, "details", "aliases", "decor", "dark")
        _clean_senses(p)
    for t in [*graph.get("items", []), *graph.get("characters", [])]:
        t["at"] = t.get("at") or ""
        for s in t.get("states") or []:
            for f in [f for f, v in s.items() if not v and f != "id"]:
                del s[f]
        texts = {k: v for k, v in (t.get("texts") or {}).items() if v}
        t.pop("texts", None)
        if texts:
            t["texts"] = texts
        answer = t.pop("answer", None) or {}
        if [x for x in answer.get("accept") or [] if x]:
            t["answer"] = {k: v for k, v in answer.items() if v}
        code = t.get("code") or {}
        t.pop("code", None)
        if [x for x in code.get("press") or [] if x]:
            t["code"] = {k: v for k, v in code.items() if v}
            t["locked"] = True
            if t.get("kind") not in ("container", "door"):
                t["kind"] = "container"
        _drop_empty(t, "fixed", "sturdy", "fragile", "initial", "key", "states", "aliases", "uses", "persona")
        light, when = t.pop("light", None), t.pop("light_when", None) or []
        if light:
            t["light"] = when or True
        _clean_senses(t)
        if t.get("key"):
            t["locked"] = True
            if t.get("kind") not in ("container", "door"):
                t["kind"] = "container"
    for e in graph.get("endings", []):
        _drop_empty(e, "fact")
    for p in graph.get("puzzles", []):
        p["needs"] = [x for x in p.get("needs") or [] if x]
    return graph


def _clean_senses(t: dict) -> None:
    senses = {k: v for k, v in (t.pop("senses", None) or {}).items() if v}
    if senses:
        t["senses"] = senses


def generate_adventure(cfg: dict, idea: str, who: str, difficulty: str, recurring: list[str], past: list[str]) -> dict:
    """A checked world graph (raises ValueError when even the repair fails)."""
    t0 = time.monotonic()
    prompt = (
        f"Idée de l'enfant : {idea or 'surprends-moi'}\nPour : {who}\n{level_rules(difficulty)}\n\n"
        "Personnages que l'enfant connaît déjà (tu peux en reprendre un, avec le même nom) :\n"
        + ("\n".join(f"- {c}" for c in recurring) or "(aucun)")
        + "\n\nAventures déjà jouées (ne refais pas la même) :\n"
        + ("\n".join(f"- {t}" for t in past) or "(aucune)")
    )
    system = _instructions(cfg)
    graph = _clean(
        engines.complete_json(
            cfg,
            system,
            prompt,
            GRAPH_SCHEMA,
            role="preparation",
            activity="adventure",
            timeout=FIRST_CALL_SECS,
            retries=0,
        ),
        difficulty,
    )
    errors, _ = check(graph)
    if not errors:
        return graph
    left = GENERATION_SECS - (time.monotonic() - t0)
    logger.info(f"🗺️ Adventure invalid ({len(errors)} errors), {'repairing' if left > 15 else 'no time to repair'}")
    if left <= 15:  # usually: the first call takes most of the time; the caller falls back
        raise ValueError("; ".join(errors))
    repair = (
        prompt + "\n\nTon monde précédent :\n" + json.dumps(graph, ensure_ascii=False)
        + "\n\nIl a ces problèmes (corrige-les, garde le reste) :\n" + "\n".join(f"- {e}" for e in errors)
    )  # fmt: skip
    graph = _clean(
        engines.complete_json(
            cfg,
            system,
            repair,
            GRAPH_SCHEMA,
            role="preparation",
            activity="adventure",
            timeout=max(10, left - 3),
            retries=0,
        ),
        difficulty,
    )
    errors, _ = check(graph)
    if errors:
        raise ValueError("; ".join(errors))
    return graph


# Words that are not an idea: « surprends-moi », « n'importe quoi », « une nouvelle aventure ».
# Words that are no idea at all: « surprends-moi », « ce que tu veux », « au hasard », « une histoire ».
FILLER = set(STOPWORDS) | {
    "surprise", "surprends", "surprendre", "importe", "quoi", "sais", "choisis", "choisir", "toi", "moi",
    "aventure", "aventures", "histoire", "histoires", "une", "nouvelle", "nouveau", "autre", "veux", "voudrais",
    "fais", "fait", "faire", "truc", "chose", "comme", "hasard", "laquelle", "lequel", "quelque", "etre", "avoir",
    "envie", "aime", "adore", "jouer", "joue", "rigolote", "rigolo", "super", "belle", "beau", "grande", "grand",
    "petite", "petit", "gros", "grosse", "vrai", "vraie", "tres", "trop", "bien", "avec", "dans", "pour", "chez",
    "plein", "tout", "tous", "ou", "peu", "plus", "sur", "sous", "pas", "sans", "aucun", "aucune", "jamais",
}  # fmt: skip
NEGATION = re.compile(r"\b(pas|sans|aucune?|jamais|plus) (de |d'|des |du |les |la |le |l')?(\w+)")
IDEA_MATCH = 2  # one idea word among the keywords or the title (2), or two in the story (1 each)


def idea_words(idea: str) -> tuple[set[str], set[str]]:
    """(the words of a child's idea, the ones refused: « pas les vikings »), as stems."""
    refused = {m.group(3) for m in NEGATION.finditer(normalize_text(idea or ""))}
    refused = _stems(" ".join(refused))
    return _stems(idea or "") - _stems(" ".join(FILLER)) - refused, refused


def idea_score(words: set[str], graph: dict, refused: AbstractSet[str] = frozenset()) -> int:
    """How well a child's idea fits an adventure: a keyword or a title noun counts double, a word of
    its story once; a refused theme rules it out. Whole words only (« chat » is not « château »)."""
    strong = _stems(" ".join([graph.get("title", ""), *graph.get("tags", [])])) - _stems(" ".join(FILLER))
    story = _stems(" ".join([graph.get("intro", ""), graph.get("goal", ""),
                             *(c.get("name", "") for c in graph.get("characters", []))]))  # fmt: skip
    if refused & (strong | story):
        return -1
    return 2 * len(words & strong) + len(words & story - strong)


def library(difficulty: str | None = None) -> list[dict]:
    """The hand-written adventures (checked by the tests)."""
    out = []
    for p in sorted(LIBRARY.glob("*.json")):
        g = json.loads(p.read_text(encoding="utf-8"))
        if difficulty in (None, g.get("difficulty")):
            out.append(g)
    return out


MODEL_DIR = LIBRARY.parent.parent.parent / "docs" / "adventure" / "model"


def generated(graph: dict) -> bool:
    """Invented for this family (`x-source`, the format's extension field; `source` before)."""
    return "generated" in (graph.get("x-source"), graph.get("source"))


def drafts(difficulty: str | None = None) -> list[dict]:
    """The reference adventures of the data model work in progress (docs/adventure/model), under
    their own title so they never replace the bank's: played by the family when `[games]
    adventure_drafts = true`, shown on the explorer page."""
    out = []
    for p in sorted(MODEL_DIR.glob("*.json")) if MODEL_DIR.is_dir() else []:
        g = json.loads(p.read_text(encoding="utf-8"))
        g["title"] = f"{g['title']} (nouvelle version)"
        if difficulty in (None, g.get("difficulty")) and not check(g)[0]:
            out.append(g)
    return out


class AdventureGame(Activity):
    tools = frozenset(ADVENTURE_TOOLS)

    def register_tools(self, llm) -> list:
        return register_tools(llm, self)

    def __init__(self, cfg: dict, memory_root, host=None, slog=None):
        super().__init__(host, slog)
        self.cfg, self.root = cfg, Path(memory_root)
        self.dir = self.root / DIR_ADVENTURES
        self.adventure: dict | None = None  # the running one (its record)
        self.world: World | None = None
        self.state: State | None = None

    # ------------------------------------------------------------------ memory (one file each)
    def _file(self, ident: str) -> Path:
        return self.dir / f"{ident}.json"

    def _all(self) -> list[dict]:
        """Every stored adventure, least recently played first."""
        out = [a for p in sorted(self.dir.glob("*.json")) if isinstance(a := load_json(p, None), dict) and a.get("id")]
        return sorted(out, key=lambda a: a.get("updated", a.get("created", "")))

    def _mine(self, player: str) -> list[dict]:
        return [a for a in self._all() if a.get("player") in (player, UNKNOWN_PLAYER)]

    def _save(self):
        if not self.adventure:
            return
        if self.state:
            self.adventure["state"] = self.state.to_dict()
        self.adventure["updated"] = now().isoformat(timespec="seconds")
        path = self._file(self.adventure["id"])
        with lock_for(path):
            atomic_write_json(path, self.adventure, indent=None)

    def _by_title(self, title: str, among: list[dict]) -> dict | None:
        if not among:
            return None
        words = _words(title or "") - TITLE_STOPWORDS
        if not words or {"derniere", "meme", "encore", "precedente"} & _words(title or ""):
            return among[-1]
        score = [(len(words & (_words(a["title"]) - TITLE_STOPWORDS)), i) for i, a in enumerate(among)]
        best, i = max(score)
        return among[i] if best else None

    def _recurring(self) -> list[str]:
        try:
            chars = JsonStore(self.root / DIR_STORIES / "univers.json", {"characters": {}}).load()["characters"]
        except (OSError, ValueError):
            return []
        ranked = sorted(chars.values(), key=lambda c: -c.get("appearances", 0))[:6]
        return [f"{c['name']} : {c.get('description', '')}" for c in ranked]

    # ------------------------------------------------------------------ start, resume, retry
    async def start(
        self,
        idea: str = "",
        difficulty: str = "",
        resume: bool = False,
        replay: str = "",
        from_checkpoint: bool = False,
        new: bool = False,
        title: str = "",
    ) -> dict:
        """`title`: the bank adventure the narrator chose (it understands the child's idea better than
        word matching, kept as a fallback); `new`: invent one even if the bank has one."""
        player = self.host.player()
        if resume or replay or from_checkpoint:
            self.cancel_preparation()  # an adventure still being written must not replace this one
            return self._reopen(player, replay, resume, from_checkpoint)
        if self.adventure:
            self.stop()
        today = now().date()
        level = child_level(self.root, player, today) if player != UNKNOWN_PLAYER else None
        if difficulty not in DIFFICULTIES:
            difficulty = "facile" if level in LITTLE_ONES or not level else "moyen"
        # No first name: a generated world joins the family's bank and may be played by a sibling.
        who = f"un enfant en {level}" if level else "un enfant de 5 à 10 ans"
        graph: dict | None
        chosen = self._by_title(title, self.bank()) if title and not new else None
        if chosen:
            graph, why = chosen, "chosen by the narrator"
        else:
            graph, why = (None, "asked for a new one") if new else self._from_bank(idea, difficulty, player)
        if graph and why == "other level":
            return {
                "proposition": {"title": graph["title"], "difficulté": graph["difficulty"]},
                "note": f"J'ai une aventure sur son idée, « {graph['title']} », mais en niveau {graph['difficulty']}. "
                f"Propose-lui : celle-là (adventure_start avec difficulty={graph['difficulty']} et la même idée), ou une "
                f"toute nouvelle en niveau {difficulty} (adventure_start avec new=true).",
            }
        if graph:
            self._ev("adventure_from_bank", title=graph["title"], why=why)
        else:  # the exception: nothing in the bank fits (the child's own idea, or everything already played)
            self._ev("adventure_generate", why=why, idea=idea[:120], difficulty=difficulty)
            past = [g["title"] for g in self.bank()][-30:]
            graph, refused = await self.prepare(
                generate_adventure, self.cfg, idea, who, difficulty, self._recurring(), past,
                failed="L'aventure n'a pas pu être préparée : propose autre chose.",
            )  # fmt: skip
            if refused and refused.get("cancelled"):
                return refused
            if refused:  # too slow, or a world the solver refused even after repair: one from the bank
                graph = self._fallback(difficulty, player)
                if not graph:
                    return refused
            elif graph:
                graph["x-source"] = "generated"  # joins the family's bank, for the other children too
        assert graph is not None
        known = next((a for a in self._mine(player) if a["title"] == graph["title"]), None)
        if known and (st := known.get("state")) and not st.get("ending") and self._load(known) is None:
            self.state = State.from_dict(st)  # the same idea again: never wipe an adventure going on
            self._refresh()
            return self._intro("Cette aventure est déjà commencée : on reprend où il en était (rappelle-le en deux "
                               "phrases). S'il veut recommencer depuis le début : adventure_start avec replay.")  # fmt: skip
        if known:  # played before: the same record, a new run, with today's version of the world
            self.adventure = known
            if not generated(graph):
                known["graph"] = graph
        else:
            self.adventure = {
                "id": uuid.uuid4().hex[:8], "title": graph["title"], "idea": idea, "player": player,
                "created": now().isoformat(timespec="minutes"), "difficulty": graph["difficulty"],
                "graph": graph, "runs": [], "state": None, "checkpoint": None,
            }  # fmt: skip
        self._new_run()
        self._ev("adventure_start", title=graph["title"], difficulty=graph["difficulty"], player=player)
        return self._intro("Présente l'aventure (titre, intro, but) en trois ou quatre phrases, puis le premier lieu.")

    # ------------------------------------------------------------------ the bank
    def bank(self, difficulty: str | None = None) -> list[dict]:
        """Every adventure Flocon can draw: the hand-written ones, then the ones generated for this
        family (checked when they were made), one per title."""
        out = {g["title"]: g for g in library(difficulty)}
        if (self.cfg.get("games") or {}).get("adventure_drafts"):
            out |= {g["title"]: g for g in drafts(difficulty)}
        for a in self._all():
            g = a.get("graph") or {}
            if generated(g) and difficulty in (None, g.get("difficulty")) and g["title"] not in out:
                if not check(g)[0]:  # made with an older engine, or damaged: not drawn any more
                    out[g["title"]] = g
        return list(out.values())

    def _played(self, player: str) -> dict[str, str]:
        """Titles this child has started, with when they last played them."""
        return {a["title"]: a.get("updated", "") for a in self._mine(player) if a.get("runs")}

    def _from_bank(self, idea: str, difficulty: str, player: str) -> tuple[dict | None, str]:
        """(an adventure of the bank, why) or (None, why it must be generated). « other level » means
        the idea exists, but at another difficulty (see `start`)."""
        played = self._played(player)
        words, refused = idea_words(idea)
        if words:

            def best(pool: list[dict]) -> dict | None:
                scored = [(idea_score(words, g, refused), g["title"] not in played, g) for g in pool]
                scored = [x for x in scored if x[0] >= IDEA_MATCH]
                return max(scored, key=lambda x: (x[0], x[1]))[2] if scored else None

            if found := best(self.bank(difficulty)):
                return found, "idea"
            if found := best(self.bank()):
                return found, "other level"
            return None, "idea not in the bank"
        pool = [g for g in self.bank(difficulty) if not (refused and idea_score(set(), g, refused) < 0)]
        fresh = [g for g in pool if g["title"] not in played]
        if fresh:
            return random.choice(fresh), "surprise"
        return None, "bank played"

    def _fallback(self, difficulty: str, player: str) -> dict | None:
        """Generation failed: the bank anyway, the least recently played first."""
        self._ev("adventure_fallback", difficulty=difficulty)
        logger.warning(f"🗺️ No generated adventure: one from the bank ({difficulty})")
        pool = self.bank(difficulty) or self.bank()
        played = self._played(player)
        pool.sort(key=lambda g: (g["title"] in played, played.get(g["title"], "")))
        return pool[0] if pool else None

    def _new_run(self, state: State | None = None, note: str = ""):
        """A new try: from the start (the « sauvegardes » are given again, like a new game), or from
        just before a loss."""
        assert self.adventure is not None
        self.world = World(self.adventure["graph"])
        self.state = state or self.world.start()
        if state is None:
            self.adventure["checkpoints_left"] = self.world.policy["checkpoints"]
            self.adventure["checkpoint"] = None
        self.adventure["runs"].append({"started": now().isoformat(timespec="minutes"), "outcome": None,
                                       **({"from": note} if note else {})})  # fmt: skip
        self._save()
        self._refresh()

    def _load(self, record: dict) -> dict | None:
        """Make `record` the running adventure; refuses a world that no longer checks (forget, edits)."""
        errors, _ = check(record.get("graph", {}))
        if errors:
            logger.warning(f"🗺️ Stored adventure « {record.get('title')} » is broken: {errors[:3]}")
            return {"error": "Cette aventure est abîmée : propose d'en commencer une nouvelle."}
        self.adventure = record
        self.world = World(record["graph"])
        return None

    def _reopen(self, player: str, replay: str, resume: bool, from_checkpoint: bool) -> dict:
        mine = self._mine(player)
        if from_checkpoint:
            lost = [a for a in mine if a.get("checkpoint")]
            if self.adventure and self.adventure.get("checkpoint"):
                lost.append(self.adventure)
            rec = lost[-1] if lost else None
            if not rec:
                return {"error": "Il n'y a pas de partie perdue à reprendre : propose de continuer, ou de rejouer "
                        "depuis le début (replay)."}  # fmt: skip
            left = rec.get("checkpoints_left")
            if left is not None and left <= 0:
                return {"error": "Plus de sauvegarde : propose de recommencer l'aventure depuis le début "
                        "(adventure_start avec replay)."}  # fmt: skip
            if err := self._load(rec):
                return err
            checkpoint, rec["checkpoint"] = State.from_dict(rec["checkpoint"]), None
            if left is not None:
                rec["checkpoints_left"] = left - 1
            self._new_run(checkpoint, note="checkpoint")
            more = "illimitées" if rec.get("checkpoints_left") is None else str(rec["checkpoints_left"])
            return self._intro(f"On reprend juste avant la bêtise (sauvegardes restantes : {more}) : rappelle où on "
                               "est, en deux phrases.")  # fmt: skip
        if resume:
            unfinished = [a for a in mine if a.get("state") and not a["state"].get("ending")]
            rec = self._by_title(replay, unfinished) if replay else (unfinished[-1] if unfinished else None)
            if not rec:
                return {"error": "Pas d'aventure en cours à reprendre.", "aventures": [a["title"] for a in mine][-6:]}
            if err := self._load(rec):
                return err
            self.state = State.from_dict(rec["state"])
            self._refresh()
            return self._intro("On reprend l'aventure : rappelle en deux phrases où on en était.")
        rec = self._by_title(replay, mine)
        if not rec:
            return {"error": "Aucune aventure trouvée avec ce nom.", "aventures": [a["title"] for a in mine][-6:]}
        if err := self._load(rec):
            return err
        self._new_run()
        self._ev("adventure_replay", title=rec["title"])
        return self._intro("On recommence cette aventure depuis le début : présente-la, puis le premier lieu.")

    def _intro(self, note: str) -> dict:
        assert self.adventure and self.world and self.state
        g = self.adventure["graph"]
        return {
            "title": g["title"], "difficulté": g["difficulty"], "intro": g.get("intro", ""), "but": g.get("goal", ""),
            "lieu": self.world.describe(self.state), "inventaire": [self.world.name(i) for i in self.state.inventory],
            "note": note,
        }  # fmt: skip

    # ------------------------------------------------------------------ the turn
    def act(self, actions: list[dict] | None, said: str = "", remember: str = "", about: str = "") -> dict:
        if not (self.adventure and self.world and self.state):
            return {"error": "Aucune aventure en cours : appelle adventure_start."}
        w, st = self.world, self.state
        if st.ending:
            return {"results": [], **self._over_note()}
        if remember:
            w.note(st, remember, about)
        intents = actions or [{"verb": "look"}]
        results: list[dict] = []
        skipped: list[dict] = []
        for n, intent in enumerate(intents):
            before = st.to_dict()
            res = w.act(st, intent)
            results.append(res)
            if res.get("outcome") == "end" and res.get("ending") == "lose":
                # « sauvegarde »: just before the mistake (a thing destroyed that was needed: before that)
                self.adventure["checkpoint"] = st.doomed.get("before") or before
            if res.get("outcome") not in ("done", "hint", "free"):
                skipped = intents[n + 1 :]  # « je prends la clé et j'ouvre la porte »: stop at the first that fails
                break
        self._remember_play(intents, results, said)
        out: dict = {"results": results, "à_portée": w.in_reach(st)}  # the ids to name things by, next time
        if skipped:
            out["pas_fait"] = skipped
            out["note_suite"] = "La suite n'a pas été faite (ça a coincé avant) : dis-le, il pourra réessayer."
        if st.ending:
            out.update(self._finish_run())
        elif nudge := w.nudge(st):
            out.update(nudge)
            out["note"] = (
                "L'enfant tourne en rond : rappelle-lui, dans l'histoire, ce qu'il peut faire (les chemins avec leur "
                "repère et leur direction, ce qu'il voit, à qui parler, son sac, une ou deux idées), sans donner la "
                "solution." if "rappel" in nudge else
                "L'enfant tourne en rond : glisse cet indice dans l'histoire, par un personnage ou un détail."
            )  # fmt: skip
        self._save()
        self._refresh()
        self._ev("adventure_act", said=said[:120], outcomes=[r.get("outcome") for r in results])
        return out

    def _remember_play(self, intents: list[dict], results: list[dict], said: str):
        """What the child did that the world doesn't model (« free », « absent »: a nickname, a pebble
        thrown, a sandcastle) is kept as a memory of the place or of who it was about: told again by
        the description, it stays true after a pause or a summary, whatever the narrator remembers."""
        assert self.world and self.state
        for intent, res in zip(intents, results, strict=False):
            if res.get("outcome") not in ("free", "absent") or not said.strip():
                continue
            about = next((x for x in (intent.get("target"), intent.get("object")) if x and
                          self.world.resolve(x, self.world.everything())[0]), "")  # fmt: skip
            self.world.note(self.state, f"il a fait : « {said.strip()[:140]} »", about)
            break  # one memory per sentence

    def _finish_run(self) -> dict:
        assert self.adventure and self.world and self.state
        st = self.state
        kind = self.world.ending(st, st.ending)["kind"] if st.ending else "stopped"
        run = self.adventure["runs"][-1]
        run.update(ended=now().isoformat(timespec="minutes"), outcome=kind, ending=st.ending, turns=st.turns,
                   score=st.score)  # fmt: skip
        self._ev("adventure_over", title=self.adventure["title"], outcome=kind, turns=st.turns, score=st.score)
        return self._over_note()

    def _over_note(self) -> dict:
        assert self.adventure and self.world and self.state
        ending = self.world.ending(self.state, self.state.ending or "")
        kind = ending.get("kind", "win")
        if kind == "win":
            fact = ending.get("fact") or self.adventure["graph"].get("fact", "")  # the ending's own, else the story's
            return {"note": "Gagné ! Raconte la fin (ending_text) avec éclat, félicite l'enfant"
                    + (", ajoute le « Le savais-tu ? » (le_savais_tu) en une phrase" if fact else "")
                    + ", puis demande-lui ce qu'il a préféré. N'appelle pas adventure_end maintenant : attends sa "
                    "réponse, et appelle-le au tour suivant avec sa réaction.",
                    **({"le_savais_tu": fact} if fact else {})}  # fmt: skip
        left = self.adventure.get("checkpoints_left")
        can = self.adventure.get("checkpoint") and (left is None or left > 0)
        retry = (f"juste avant la bêtise (adventure_start avec from_checkpoint, sauvegardes restantes : "
                 f"{'illimitées' if left is None else left}) ou " if can else "")  # fmt: skip
        stuck = (" C'est maintenant qu'il se rend compte qu'une chose indispensable a disparu : dis-le simplement, "
                 "sans gronder." if self.state.ending == STUCK else "")  # fmt: skip
        return {
            "note": f"Perdu…{stuck} Raconte la fin (ending_text) avec douceur et humour, puis propose de réessayer : "
            f"{retry}depuis le début (adventure_start avec replay). S'il ne veut pas, appelle adventure_end."
        }

    def end(self, reaction: str = "") -> dict:
        if not self.adventure:
            return {"error": "Aucune aventure en cours."}
        run = self.adventure["runs"][-1] if self.adventure["runs"] else {}
        if not run.get("outcome"):
            run.update(outcome="stopped", ended=now().isoformat(timespec="minutes"))
        run["reaction"] = reaction.strip()
        self._save()
        title = self.adventure["title"]
        self._ev("adventure_end", title=title, outcome=run.get("outcome"), reaction=reaction[:200])
        self.adventure = self.world = self.state = None
        self._refresh()
        out = {"saved": title, "note": "Elle est gardée en mémoire : on pourra la rejouer. Propose autre chose."}
        if offer := self.host.next_offer():
            out["propose"] = offer
        return out

    def stop(self):
        """The activity ends without adventure_end: the state is kept, to resume later."""
        self.cancel_preparation()
        if self.adventure:
            self._save()
            self._ev("adventure_paused", title=self.adventure["title"])
        self.adventure = self.world = self.state = None

    # ------------------------------------------------------------------ prompt, labels, names
    def _ev(self, type_, **kw):
        self.slog.event(type_, **kw)

    def _refresh(self):
        self.host.refresh_prompt_soon()

    def _activity_on(self) -> bool:
        skills = getattr(self.host, "skills", None)
        return bool(skills and getattr(skills, "active", None) == "adventure")

    def prompt_section(self) -> str:
        if not (self.adventure and self.world and self.state):
            return self._stored_section() if self._activity_on() else ""
        w, st, g = self.world, self.state, self.adventure["graph"]
        here = w.describe(st)
        exits = ", ".join(
            f"{x['vers']} ({x['direction']})" + (" — fermée" if "fermée" in x else "") for x in here["sorties"]
        )
        notes = "; ".join(f"{w.name(k, st)} : {n}" for k, ns in st.notes.items() for n in ns[-3:])
        return (
            f"## Aventure en cours : « {g['title']} » ({g['difficulty']})\n"
            f"But : {g.get('goal', '')}\nLieu : {here['lieu']}. Ici : {', '.join(here['ici']) or 'rien'}. "
            f"Personnages : {', '.join(here['personnages']) or 'personne'}. Sorties : {exits}.\n"
            f"À portée (désigne-les par leur id) : {'; '.join(f'{k} = {v}' for k, v in w.in_reach(st).items())}.\n"
            f"Sac : {', '.join(w.name(i, st) for i in st.inventory) or 'vide'}."
            + (f"\nSouvenirs à garder (ce qu'il a fait, ce qui a été inventé) : {notes}" if notes else "")
            + "\nC'est le programme qui sait ce qui est vrai : pour chaque action de l'enfant dans l'aventure, "
            "appelle adventure_act, puis raconte le résultat. Ne révèle jamais la solution."
        )

    def _stored_section(self) -> str:
        """While the activity is chosen but no adventure is loaded: what can be resumed or replayed."""
        player = self.host.player()
        mine = self._mine(player)
        played = self._played(player)
        catalog = [
            f"- « {g['title']} » ({g['difficulty']}) : {', '.join(g.get('tags', [])[:4])}"
            + (" — déjà jouée" if g["title"] in played else "")
            for d in DIFFICULTIES for g in self.bank(d)
        ][:CATALOG_SHOWN]  # fmt: skip
        discover = (
            "## La banque d'aventures (choisis toi-même celle qui va avec son idée et passe son titre à "
            "adventure_start ; sans idée, propose-lui deux thèmes pas encore joués ; si rien ne va, une nouvelle "
            "sera inventée)\n" + "\n".join(catalog)
        ) if catalog else ""  # fmt: skip
        if not mine:
            return discover
        lines = []
        for a in mine[-5:]:
            st, last = a.get("state") or {}, (a.get("runs") or [{}])[-1]
            status = ("pas finie" if st and not st.get("ending") else
                      {"win": "gagnée", "lose": "perdue", "stopped": "arrêtée"}.get(last.get("outcome") or "", "jouée"))  # fmt: skip
            lines.append(f"- « {a['title']} » ({a.get('difficulty')}) : {status}")
        kept = "## Aventures gardées (resume pour une pas finie, replay pour rejouer)\n" + "\n".join(lines)
        return kept + ("\n" + discover if discover else "")

    def on_user_message(self, text: str) -> str | None:
        if not self.state:
            return None
        return "aventure : traduis ce que dit l'enfant en actions pour adventure_act (sauf s'il parle d'autre chose)"

    def names(self) -> list[str]:
        if not self.world:
            return []
        names = [e.get("name", "") for t in (self.world.chars, self.world.items, self.world.places) for e in t.values()]
        return [n for n in dict.fromkeys(names) if n][:STT_NAMES]


