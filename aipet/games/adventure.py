def level_rules(difficulty: str) -> str:
    """The difficulty for the generator, with the limits the solver will check (French)."""
    spec = DIFFICULTIES[difficulty]
    (pl, ph), (sl, sh), (ll, lh) = spec["places"], spec["steps"], spec["loses"]
    zl, zh = spec["puzzles"]
    loses = f"{ll} à {lh} façons de perdre" if ll != lh else f"{ll} façon(s) de perdre"
    return (
        f"Difficulté {difficulty} : {LEVEL_SHAPE[difficulty]}. Entre {pl} et {ph} lieux, {loses} (bien annoncées). "
        f"La façon la plus courte de gagner doit résoudre entre {zl} et {zh} énigmes (actions et ouvertures) et "
        f"prendre entre {sl} et {sh} étapes (chaque déplacement, chaque objet ramassé et chaque action comptent)."
    )


